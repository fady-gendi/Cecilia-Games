/* Builds shared/emoji-old-ipad.js: pictures for every emoji in the games that an old iPad (iOS 9) cannot draw.
 * Usage:  npm pack @twemoji/svg@15.0.0 && tar xzf twemoji-svg-15.0.0.tgz   (gives ./package/*.svg)
 *         node tools/build-emoji-fallback.cjs ./package
 * Pictures: Twemoji by Twitter / jdecked, CC-BY 4.0 (https://github.com/jdecked/twemoji). */
const fs=require('fs'),path=require('path');
const SVG=process.argv[2]||'package',ROOT=path.join(__dirname,'..');
const OK=[[0x1F300,0x1F320],[0x1F330,0x1F335],[0x1F337,0x1F37C],[0x1F380,0x1F393],[0x1F3A0,0x1F3C4],[0x1F3C6,0x1F3CA],[0x1F3E0,0x1F3F0],[0x1F400,0x1F43E],[0x1F440,0x1F440],
 [0x1F442,0x1F4F7],[0x1F4F9,0x1F4FC],[0x1F500,0x1F53D],[0x1F550,0x1F567],[0x1F5FB,0x1F640],[0x1F645,0x1F64F],[0x1F680,0x1F6C5],[0x1F1E6,0x1F1FF],[0x1F004,0x1F004],[0x1F0CF,0x1F0CF],[0x1F170,0x1F251]];
/* symbols below U+1F000 that only became colour emoji after iOS 9 */
const LATE_BMP='☄☘☠☢☣☦☪☮☯☸☹⚒⚔⚖⚗⚙⚛⚜⚰⚱⛈⛏⛑⛓⛩⛰⛱⛴⛷⛸⛹✡❣☃☂⏱⏲⏯⏮⏭⏸⏹⏺🕉';
function late(c){return c>=0x1F000?!OK.some(r=>c>=r[0]&&c<=r[1]):LATE_BMP.indexOf(String.fromCodePoint(c))>=0}
const pages=fs.readdirSync(ROOT).filter(d=>fs.existsSync(path.join(ROOT,d,'index.html'))).map(d=>path.join(ROOT,d,'index.html'));
const found=new Set();
for(const f of pages){const t=fs.readFileSync(f,'utf8');for(const ch of t){const c=ch.codePointAt(0);if(late(c))found.add(ch)}}
const map={};let miss=[];
for(const ch of [...found].sort()){const file=path.join(SVG,ch.codePointAt(0).toString(16)+'.svg');
 if(!fs.existsSync(file)){miss.push(ch);continue}
 map[ch]=fs.readFileSync(file,'utf8').replace(/\s+/g,' ').replace(/<\?xml[^>]*>/,'').trim()}
const out='/* Generated by tools/build-emoji-fallback.cjs. Do not edit by hand.\n * Pictures for emoji that old iPads cannot draw. Loaded by shared/cecilia.js only on such devices.\n * Twemoji graphics by Twitter / jdecked, licensed CC-BY 4.0. */\nwindow.CeciliaEmojiPictures='+JSON.stringify(map)+';\n';
fs.writeFileSync(path.join(ROOT,'shared','emoji-old-ipad.js'),out);
console.log('emoji pictures:',Object.keys(map).length,'bytes:',out.length,'missing:',miss.join(' '));
